"""Maintainer-only official protobuf generation; never invoked by product CMake."""

from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import zipfile


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def output_paths(lock: dict, family_name: str = "all") -> set[str]:
    return {str(Path(entry["path"]).with_suffix(suffix)).replace("\\", "/")
            for family in lock["families"] if family_name in ("all", family["name"])
            for entry in family["files"] for suffix in (".pb.c", ".pb.h")}


def previous_manifest(output: Path, expected: set[str]) -> dict[str, str]:
    rows = {}
    for line in (output / "generated.sha256").read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line:
            continue
        match = re.fullmatch(r"([0-9a-f]{64})  ([A-Za-z0-9_./-]+\.pb\.[ch])", line)
        if not match or match[2] not in expected or match[2] in rows:
            raise RuntimeError("Malformed or unexpected generated manifest entry")
        rows[match[2]] = match[1]
    if rows.keys() != expected:
        raise RuntimeError("Generated manifest does not match the locked schema closure")
    return rows


def write_generated_manifest(output: Path, lock: dict) -> None:
    expected = output_paths(lock)
    files = {path.relative_to(output).as_posix() for path in output.rglob("*")
             if path.is_file() and path.relative_to(output).as_posix() != "generated.sha256"}
    if files != expected:
        raise RuntimeError("Generated output file set differs from the locked schema closure")
    rows = ["# Generated by scripts/telemetry/generate_native_schema.py; SHA-256 and relative output path."]
    for name in sorted(expected):
        path = output / name
        header = path.read_bytes()[:256]
        if path.is_symlink() or not re.match(
                rb"/\* Automatically generated nanopb (constant definitions|header) \*/\r?\n/\* Generated by nanopb-0\.4\.9\.2 \*/", header):
            raise RuntimeError("Official nanopb output marker missing: " + name)
        rows.append(digest(path) + "  " + name)
    (output / "generated.sha256").write_bytes(("\n".join(rows) + "\n").encode("utf-8"))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--protoc", required=True, type=Path)
    parser.add_argument("--protoc-archive", required=True, type=Path,
                        help="Official pinned protoc release zip used to supply the executable/includes")
    parser.add_argument("--protoc-include", required=True, type=Path)
    parser.add_argument("--nanopb-source", required=True, type=Path)
    parser.add_argument("--schema-sources", required=True, type=Path,
                        help="Offline directory containing tensorboard/ and otlp/ official source trees")
    parser.add_argument("--family", choices=("tensorboard", "otlp", "all"), default="all")
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[2] /
                        "src/jyppx/liuding/telemetry_native/detail/telemetry_proto")
    args = parser.parse_args()
    lock = json.loads(Path(__file__).with_name("native_schema.lock.json").read_text(encoding="utf-8"))
    protoc = args.protoc.resolve(strict=True)
    protoc_include = args.protoc_include.resolve(strict=True)
    nanopb = args.nanopb_source.resolve(strict=True)
    schemas = args.schema_sources.resolve(strict=True)
    output = args.output.resolve()
    # A partial generation may not silently bless modified unselected output.
    unchanged = {}
    if args.family != "all":
        previous = previous_manifest(output, output_paths(lock))
        unchanged = {name: previous[name] for name in output_paths(lock) - output_paths(lock, args.family)}
        if any((output / name).is_symlink() or digest(output / name) != expected
               for name, expected in unchanged.items()):
            raise RuntimeError("Unselected generated family changed; use a complete official regeneration")
    if importlib.metadata.version("protobuf") != lock["tools"]["python_protobuf"]:
        raise RuntimeError("Use the pinned maintenance protobuf runtime")
    archive_digest = digest(args.protoc_archive)
    if archive_digest not in {entry["sha256"] for entry in lock["tools"]["protoc_archives"]}:
        raise RuntimeError("Pinned official protoc archive mismatch")
    with zipfile.ZipFile(args.protoc_archive) as archive:
        executable = "bin/protoc.exe" if os.name == "nt" else "bin/protoc"
        if protoc.read_bytes() != archive.read(executable):
            raise RuntimeError("Protoc executable differs from the verified official distribution")
        for entry in archive.namelist():
            if entry.startswith("include/") and not entry.endswith("/"):
                if (protoc_include / entry.removeprefix("include/")).read_bytes() != archive.read(entry):
                    raise RuntimeError("Protoc include differs from the verified official distribution")
    version = subprocess.run([str(protoc), "--version"], capture_output=True, text=True,
                             check=True).stdout.strip()
    if version != "libprotoc " + lock["tools"]["protoc"]:
        raise RuntimeError("Official protoc version mismatch")
    for source in lock["nanopb_source_files"]:
        if digest(nanopb / source["path"]) != source["sha256"]:
            raise RuntimeError("Pinned official nanopb source mismatch: " + source["path"])
    with tempfile.TemporaryDirectory(prefix="ld-schema-") as temporary:
        work = Path(temporary)
        generated = work / "g"
        generated.mkdir()
        env = dict(os.environ)
        env["PATH"] = str(protoc.parent) + os.pathsep + env.get("PATH", "")
        env["PYTHONPATH"] = str(work)
        env["NANOPB_PB2_NO_REBUILD"] = "1"
        env["PYTHONDONTWRITEBYTECODE"] = "1"

        def run(argv: list[str]) -> None:
            subprocess.run(argv, cwd=work, env=env, check=True)

        run([str(protoc), f"-I{nanopb / 'generator/proto'}",
             f"-I{protoc_include}", f"--python_out={work}",
             str(nanopb / "generator/proto/nanopb.proto")])
        for family in lock["families"]:
            if args.family not in ("all", family["name"]):
                continue
            schema_root = schemas / family["name"]
            options_root = work / "options" / family["name"]
            descriptors = []
            for entry in family["files"]:
                source_path = schema_root / entry["path"]
                if digest(source_path) != entry["sha256"]:
                    raise RuntimeError("Pinned official schema mismatch: " + entry["path"])
                text = source_path.read_text(encoding="utf-8")
                package = re.search(r"(?m)^package\s+([\w.]+)\s*;", text)
                if package is None:
                    raise RuntimeError("Official schema package missing")
                options_path = options_root / Path(entry["path"]).with_suffix(".options")
                options_path.parent.mkdir(parents=True, exist_ok=True)
                options = [f'* package:"jyppx.liuding.telemetry.{package.group(1)}"',
                           "* fallback_type:FT_CALLBACK"]
                if entry["path"] == "tensorboard/compat/proto/tensor.proto":
                    options.append("*.TensorProto.double_val max_count:1")
                options_path.write_text("\n".join(options) + "\n", encoding="utf-8")
                descriptor = work / "d" / family["name"] / (entry["path"] + ".pb")
                descriptor.parent.mkdir(parents=True, exist_ok=True)
                run([str(protoc), f"-I{schema_root}", "--include_imports",
                     f"--descriptor_set_out={descriptor}", entry["path"]])
                descriptors.append(str(descriptor))
            run([sys.executable, str(nanopb / "generator/nanopb_generator.py"),
                 "--no-timestamp", "--error-on-unmatched", "-D", str(generated),
                 "-I", str(options_root), *descriptors])
        files = [path for path in generated.rglob("*") if path.is_file()]
        expected = 2 * sum(len(family["files"]) for family in lock["families"]
                           if args.family in ("all", family["name"]))
        if len(files) != expected:
            raise RuntimeError("Official generator output closure is incomplete")
        for source_path in files:
            target = output / source_path.relative_to(generated)
            if os.name == "nt":
                target = Path("\\\\?\\" + str(target))
            target.parent.mkdir(parents=True, exist_ok=True)
            # Reproducible LF output; no edits to generated tokens or schemas.
            target.write_bytes(source_path.read_text(encoding="utf-8").encode("utf-8"))
        if any(digest(output / name) != expected for name, expected in unchanged.items()):
            raise RuntimeError("Unselected generated family changed during generation")
        write_generated_manifest(output, lock)


if __name__ == "__main__":
    main()
