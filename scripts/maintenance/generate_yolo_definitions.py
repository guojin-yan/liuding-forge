"""Development-only compiler of the frozen YAML inventory into numeric C++ data.

Uses a deliberately closed literal grammar; never imports or evaluates upstream
Python. Not installed and not used by any product preparation/runtime path.
Generated configuration data retains its upstream AGPL-3.0 license.
"""

import argparse
import ast
import hashlib
import json
import pathlib
import re


def literal(text):
    def visit(node):
        if isinstance(node, ast.List):
            return [visit(value) for value in node.elts]
        if isinstance(node, ast.Constant):
            return node.value
        if isinstance(node, ast.Name):
            return {"True": True, "False": False, "None": None}.get(node.id, node.id)
        if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
            return node.value.id + "." + node.attr
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
            return -visit(node.operand)
        raise ValueError("Unsupported configuration expression")
    return visit(ast.parse(text, mode="eval").body)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference-root", type=pathlib.Path, required=True)
    parser.add_argument("--inventory", type=pathlib.Path, required=True)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    args = parser.parse_args()
    entries = json.loads(args.inventory.read_text(encoding="utf-8-sig"))["entries"]
    lines = [
        "// Product: 六丁炼算 (Liuding Forge)",
        "// Project alias: JYPPX Training Framework",
        "// Numeric architecture data derived from Ultralytics 8.4.177 YAML configurations.",
        "// Copyright Ultralytics. SPDX-License-Identifier: AGPL-3.0-only",
        "// See third_party/licenses/ultralytics-AGPL-3.0.txt and MODEL_PROVENANCE.md.",
        "// Generated by scripts/maintenance/generate_yolo_definitions.py; do not edit.",
        "const std::vector<GraphSpec>& Graphs() {",
        "  static const std::vector<GraphSpec> graphs{",
    ]
    count = 0
    for entry in entries:
        if entry["scope"] != "release_required":
            continue
        raw = (args.reference_root / entry["path"]).read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        if digest != entry["sha256"]:
            raise ValueError("Reference changed: " + entry["path"])
        scales, layers = [], []
        section = ""
        for full_line in raw.decode("utf-8-sig").splitlines():
            line = full_line.split("#", 1)[0].strip()
            if not line:
                continue
            if line in ("scales:", "backbone:", "head:"):
                section = line[:-1]
            elif section == "scales" and re.match(r"[nsm lx]:".replace(" ", ""), line):
                scales.append(literal(line.split(":", 1)[1].strip()))
            elif section in ("backbone", "head") and line.startswith("- "):
                source, repeat, kind, arguments = literal(line[2:])
                source = source if isinstance(source, list) else [source]
                numeric = [float(x) if isinstance(x, (int, float)) else
                           {"nc": -100, "kpt_shape": -101}.get(str(x), 0)
                           for x in arguments]
                layers.append((source, repeat, kind, numeric))
        if len(scales) != 5 or not layers:
            raise ValueError("Expected five scales and a graph: " + entry["path"])
        key = pathlib.PurePosixPath(entry["path"]).stem
        lines.append("    {" + json.dumps(key) + ", " + json.dumps(entry["path"]) + ", " +
                     json.dumps(digest) + ", {{" +
                     ", ".join("{" + ", ".join(str(x) for x in s) + "}" for s in scales) + "}}, {")
        for source, repeat, kind, numeric in layers:
            lines.append("      {{" + ", ".join(str(x) for x in source) + "}, " + str(repeat) +
                         ", " + json.dumps(kind) + ", {" + ", ".join(str(x) for x in numeric) + "}},")
        lines.append("    }},")
        count += 1
    lines += ["  };", "  return graphs;", "}", ""]
    if count != 29:
        raise ValueError("Unexpected required graph count: " + str(count))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Generated {count} graphs / {count * 5} scale selections")


if __name__ == "__main__":
    main()
