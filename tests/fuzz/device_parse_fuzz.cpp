#include <jyppx/core/device.hpp>

#include <cstddef>
#include <cstdint>
#include <exception>
#include <string>

namespace {

/// Maximum input retained by this harness, including deliberately oversized
/// values that exercise the public parser's 64-byte resource limit.
constexpr std::size_t kMaxFuzzInputLength = 256;

}  // namespace

/**
 * @brief Exercises the public device parser with arbitrary bounded bytes.
 *
 * Invalid input is part of the parser contract and may throw a standard
 * exception. Sanitizer findings, non-standard escapes, and process failures
 * remain visible to libFuzzer as defects.
 *
 * @param data Byte sequence generated by libFuzzer.
 * @param size Number of bytes available at `data`.
 * @return Always zero after a handled parse attempt.
 */
extern "C" int LLVMFuzzerTestOneInput(const std::uint8_t* data,
                                      std::size_t size) {
  if (size > kMaxFuzzInputLength) {
    return 0;
  }

  const std::string input(reinterpret_cast<const char*>(data), size);
  try {
    static_cast<void>(jyppx::parse_device(input));
  } catch (const std::exception&) {
    // Rejected strings are expected; sanitizer failures are not caught.
  }
  return 0;
}
