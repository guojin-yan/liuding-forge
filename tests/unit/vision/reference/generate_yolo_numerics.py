"""Generate a small, independent FP32 detection reference from local upstream.

Development only. Requires the explicitly supplied Ultralytics 8.4.177 source
and PyTorch; never downloads packages, data or weights.
"""
import argparse
import hashlib
import os
from pathlib import Path
import sys
from types import SimpleNamespace


def generate(torch, criterion_type, assigner_type, source_root, output):
    torch.set_num_threads(1)
    torch.set_num_interop_threads(1)
    raw = (((torch.arange(2 * 18 * 21) * 37) % 251 - 125).float() / 32).reshape(2, 18, 21)
    raw.requires_grad_(True)
    targets = torch.tensor([[0., 0., 4., 4., 28., 28.], [1., 1., 2., 6., 30., 30.]])
    head = SimpleNamespace(nc=2, reg_max=4, stride=torch.tensor([8., 16., 32.]))
    model = SimpleNamespace(parameters=lambda: iter([raw]), model=[head],
                            args=SimpleNamespace(box=7.5, cls=0.5, dfl=1.5))
    criterion = criterion_type(model)
    xyxy = targets[:, 2:]
    batch = dict(batch_idx=targets[:, 0], cls=targets[:, 1:2],
                 bboxes=torch.cat(((xyxy[:, :2] + xyxy[:, 2:]) / 2,
                                   xyxy[:, 2:] - xyxy[:, :2]), 1) / 32)
    predictions = dict(boxes=raw[:, :16], scores=raw[:, 16:],
                       feats=[torch.zeros(2, 18, side, side) for side in [4, 2, 1]])
    losses, _ = criterion(predictions, batch)
    total = losses.sum()
    total.backward()
    # One anchor avoids differences in the minimum-box candidate policy and
    # isolates the CIoU stabilization term on a valid very small box.
    tiny = torch.tensor([[[3.995, 3.995, 4.005, 4.005]]])
    tiny_result = assigner_type(topk=1, num_classes=2, alpha=0.5, beta=6., stride=[8])(
        torch.tensor([[[0.5, 0.25]]]), tiny, torch.tensor([[4., 4.]]),
        torch.zeros(1, 1, 1), tiny.clone(), torch.ones(1, 1, 1, dtype=torch.bool))
    records = dict(loss=torch.cat((total.detach().view(1), losses.detach() / 2)),
                   gradient=raw.grad, tiny_scores=tiny_result[2])
    lines = [
        '// Copyright 2026 JYPPX Training Framework Contributors',
        '// Product: 六丁炼算 (Liuding Forge)',
        '// Project alias: JYPPX Training Framework',
        '// Licensed under the Apache License, Version 2.0.',
        '// Generated by reference/generate_yolo_numerics.py; do not edit.',
        '// Independent Ultralytics 8.4.177 FP32 detection reference.',
        '// Upstream source is subject to the existing AGPL-3.0 provenance.',
        '// PyTorch: ' + str(torch.__version__),
    ]
    for relative in ['utils/loss.py', 'utils/tal.py', 'utils/metrics.py', 'utils/ops.py']:
        digest = hashlib.sha256((source_root / 'ultralytics' / relative).read_bytes()).hexdigest()
        lines.append('// ' + relative + ' SHA256: ' + digest)
    lines += ['#pragma once', '#include <array>', 'namespace yolo_numerics_reference {']
    for name, value in records.items():
        values = [format(v, '.9g') for v in value.detach().flatten().tolist()]
        values = [v + ('.0' if '.' not in v and 'e' not in v else '') + 'F' for v in values]
        lines.append('inline constexpr std::array<float, ' + str(len(values)) + '> ' + name + '{{')
        lines.extend('    ' + ', '.join(values[i:i+6]) + ',' for i in range(0, len(values), 6))
        lines.append('}};')
    lines.append('}  // namespace yolo_numerics_reference')
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('Independent detection reference:', output.name, 'loss=', float(total.detach()), flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--upstream-root', type=Path, required=True)
    parser.add_argument('--output-header', type=Path, required=True)
    args = parser.parse_args()
    os.environ.update(YOLO_AUTOINSTALL="false", YOLO_OFFLINE="true")
    sys.path.insert(0, str(args.upstream_root.resolve()))
    import torch
    from ultralytics.utils.loss import v8DetectionLoss
    from ultralytics.utils.tal import TaskAlignedAssigner
    generate(torch, v8DetectionLoss, TaskAlignedAssigner, args.upstream_root, args.output_header)


if __name__ == '__main__':
    main()
