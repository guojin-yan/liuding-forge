"""Generate independent YOLO26 E2E loss/assignment references from local source.

Development only: Ultralytics 8.4.177 and PyTorch, no downloads or weights.
"""
import argparse
import hashlib
import os
from pathlib import Path
import sys
from types import SimpleNamespace


def generate(torch, criterion_type, source_root, output):
    torch.set_num_threads(1)
    torch.set_num_interop_threads(1)
    base = torch.arange(2 * 7 * 85).reshape(2, 7, 85)
    many = ((base * 37 % 251 - 125).float() / 32).requires_grad_(True)
    one = ((base * 19 % 229 - 114).float() / 32).requires_grad_(True)
    # Positive distances give overlaps; distinct logits avoid tie-only probes.
    with torch.no_grad():
        many[:, :4].abs_().add_(0.25)
        one[:, :4].abs_().add_(0.5)
    targets = torch.tensor([[0., 0., 10., 10., 14., 14.],
                            [0., 1., 8., 8., 30., 29.],
                            [0., 2., 24., 16., 50., 54.],
                            [1., 1., 29., 29., 35., 35.],
                            [1., 0., 6., 10., 42., 50.]])
    xyxy = targets[:, 2:]
    batch = dict(batch_idx=targets[:, 0], cls=targets[:, 1:2],
                 bboxes=torch.cat(((xyxy[:, :2] + xyxy[:, 2:]) / 2,
                                   xyxy[:, 2:] - xyxy[:, :2]), 1) / 64)
    head = SimpleNamespace(nc=3, reg_max=1, stride=torch.tensor([8., 16., 32., 64.]))
    model = SimpleNamespace(parameters=lambda: iter([many]), model=[head],
                            args=SimpleNamespace(box=7.5, cls=0.5, dfl=1.5, epochs=100))

    def predictions(raw):
        return dict(boxes=raw[:, :4], scores=raw[:, 4:],
                    feats=[torch.zeros(2, 7, s, s) for s in [8, 4, 2, 1]])

    prediction = dict(one2many=predictions(many), one2one=predictions(one))
    records = {}
    losses = []
    for epoch in [0, 1, 99, 100]:
        criterion = criterion_type(model)
        for _ in range(epoch):
            criterion.update()
        loss, _ = criterion(prediction, batch)
        losses.append(loss.sum().detach())
        if epoch == 0:
            loss.sum().backward()
            records['many_gradient'] = many.grad
            records['one_gradient'] = one.grad
            # Directly expose secondary filtering and small-box candidates.
            for name, branch, value in [('many', criterion.one2many, many),
                                         ('one', criterion.one2one, one)]:
                assigned = branch.get_assigned_targets_and_loss(predictions(value), batch)[0]
                fg, indices, boxes, anchors, strides = assigned
                raw_prediction = predictions(value)
                decoded = branch.bbox_decode(anchors, raw_prediction['boxes'].permute(0, 2, 1)) * strides
                gt = branch.preprocess(torch.cat((targets[:, :2], batch['bboxes']), 1), 2,
                                       torch.tensor([64., 64., 64., 64.]))
                full = branch.assigner(raw_prediction['scores'].permute(0, 2, 1).detach().sigmoid(),
                    decoded.detach(), anchors * strides, gt[:, :, :1], gt[:, :, 1:],
                    gt[:, :, 1:].sum(2, keepdim=True).gt_(0))
                records[name + '_scores'] = full[2]
                records[name + '_foreground'] = fg.float()
                records[name + '_indices'] = torch.where(fg, indices + torch.tensor([[0], [3]]), -1).float()
    records['losses'] = torch.stack(losses)
    model.args.epochs = 1
    criterion = criterion_type(model)
    criterion.update()
    records['single_epoch_loss'] = criterion(prediction, batch)[0].sum().detach().reshape(1)
    lines = [
        '// Copyright 2026 JYPPX Training Framework Contributors',
        '// Product: 六丁炼算 (Liuding Forge)',
        '// Project alias: JYPPX Training Framework',
        '// Licensed under the Apache License, Version 2.0.',
        '// Generated by reference/generate_yolo26_numerics.py; do not edit.',
        '// Independent Ultralytics 8.4.177 E2ELoss FP32 reference.',
        '// Existing AGPL-3.0 upstream provenance applies.',
        '// PyTorch: ' + str(torch.__version__),
    ]
    for relative in ['utils/loss.py', 'utils/tal.py', 'utils/metrics.py', 'utils/ops.py']:
        lines.append('// ' + relative + ' SHA256: ' + hashlib.sha256(
            (source_root / 'ultralytics' / relative).read_bytes()).hexdigest())
    lines += ['#pragma once', '#include <array>', 'namespace yolo26_numerics_reference {']
    for name, value in records.items():
        values = [format(v, '.9g') for v in value.detach().flatten().tolist()]
        values = [v + ('.0' if '.' not in v and 'e' not in v else '') + 'F' for v in values]
        lines.append(f'inline constexpr std::array<float, {len(values)}> {name}' + '{{')
        lines.extend('    ' + ', '.join(values[i:i+6]) + ',' for i in range(0, len(values), 6))
        lines.append('}};')
    lines.append('}  // namespace yolo26_numerics_reference')
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('Independent E2E reference losses:', [float(x) for x in losses], flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--upstream-root', type=Path, required=True)
    parser.add_argument('--output-header', type=Path, required=True)
    args = parser.parse_args()
    os.environ.update(YOLO_AUTOINSTALL='false', YOLO_OFFLINE='true')
    sys.path.insert(0, str(args.upstream_root.resolve()))
    import torch
    from ultralytics.utils.loss import E2ELoss
    generate(torch, E2ELoss, args.upstream_root, args.output_header)


if __name__ == '__main__':
    main()
