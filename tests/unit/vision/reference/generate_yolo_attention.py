"""Generate isolated official spatial-attention output and QKV adjoints.

Development only. Requires the existing pinned local source and AMD PyTorch;
does not download dependencies or enter the installed product runtime.
"""
import argparse
import hashlib
import os
from pathlib import Path
import sys


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    source = args.source.resolve()
    block = source / 'ultralytics/nn/modules/block.py'
    expected = 'eaa56f73fc3d499ee403ef50b9a100a84c79710c891cf6393bccebb0c2d3eeb0'
    if hashlib.sha256(block.read_bytes()).hexdigest() != expected:
        parser.error('Expected frozen cb13d5f9 Attention source')
    if args.output.exists():
        parser.error('Output must not exist')
    os.environ.update(YOLO_OFFLINE='true', YOLO_AUTOINSTALL='false')
    sys.path.insert(0, str(source))
    import torch
    from ultralytics.nn.modules.block import Attention
    if torch.__version__ != '2.14.0+rocm10.1.0':
        parser.error('Reference requires torch 2.14.0+rocm10.1.0; CPU execution')
    torch.set_num_threads(1)

    class Packed(torch.nn.Module):
        def __init__(self, value):
            super().__init__()
            self.value = torch.nn.Parameter(value)

        def forward(self, unused):
            return self.value

    class Zero(torch.nn.Module):
        def forward(self, value):
            return torch.zeros_like(value)

    lines = [
        '// Copyright 2026 JYPPX Training Framework Contributors',
        '// Product: 六丁炼算 (Liuding Forge)',
        '// Project alias: JYPPX Training Framework',
        '// Licensed under the Apache License, Version 2.0.',
        '// Generated by reference/generate_yolo_attention.py; do not edit.',
        '// Official cb13d5f9 Attention.forward; existing AGPL-3.0 provenance applies.',
        '// block.py SHA256: ' + expected,
        '// Torch 2.14.0+rocm10.1.0; CPU FP32 / CUDA FP16 autocast.',
        '// Fixed QKV, identity projection, zero PE; official forward unchanged.',
        '#ifndef JYPPX_YOLO_ATTENTION_REFERENCE_HPP',
        '#define JYPPX_YOLO_ATTENTION_REFERENCE_HPP',
        '#include <array>', 'namespace yolo_attention_reference {',
    ]
    for dtype, name in [(torch.float32, 'fp32'), (torch.float16, 'fp16')]:
        device = 'cuda' if dtype == torch.float16 else 'cpu'
        packed = ((((torch.arange(144) * 37) % 101).float() - 50)
                  .reshape(1, 24, 2, 3) / 23 * 4).to(device=device, dtype=dtype)
        model = Attention(12, 2)
        model.qkv = Packed(packed)
        model.proj = torch.nn.Identity()
        model.pe = Zero()
        with torch.autocast('cuda', dtype=torch.float16,
                            enabled=dtype == torch.float16):
            output = model(torch.zeros(1, 12, 2, 3, device=device)).float()
            loss = output.square().mean()
        loss.backward()
        for key, value in [('packed', packed), ('output', output),
                           ('gradient', model.qkv.value.grad)]:
            values = value.detach().float().flatten().tolist()
            lines.append(f'inline constexpr std::array<float, {len(values)}> {name}_{key} = {{')
            lines.extend('  ' + ', '.join(f'{v:.10e}f' for v in values[i:i+6]) + ','
                         for i in range(0, len(values), 6))
            lines.append('};')
    lines.extend(['}  // namespace yolo_attention_reference', '#endif'])
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
