TEST_F(BundleSigningDirectory,
       RejectsMetadataChangesDomainReplayAndExtraFakeSigner) {
  const auto result = PublishSigned();
  const auto verify = signing::make_ed25519_verifier(Policy());
  const auto& signature = result.published.manifest.signatures[0];
  auto changed = result.published.manifest;
  changed.runtime.backend_version = "2.0.0";
  EXPECT_FALSE(
      verify(signature, Bytes(interop::model_bundle_signing_payload(changed))));
  changed = result.published.manifest;
  changed.schema_version = 1U;
  EXPECT_FALSE(
      verify(signature, Bytes(interop::model_bundle_signing_payload(changed))));
  changed = result.published.manifest;
  auto forged = signature;
  forged.key_id = "other-signer";
  changed.signatures.push_back(forged);
  Manifest(changed);
  EXPECT_THROW(
      interop::verify_model_bundle_directory(
          base_ / "signed", signing::trusted_ed25519_options(Policy())),
      jyppx::liuding::Error);
  changed.signatures[1] = signature;
  EXPECT_THROW(interop::serialize_model_bundle_manifest(changed),
               jyppx::liuding::Error);
}

TEST_F(BundleSigningDirectory,
       ExistingDestinationsAndMismatchedPoliciesAreNeverOverwritten) {
  const auto source = PublishUnsigned();
  std::filesystem::create_directory(base_ / "existing");
  Write(base_ / "existing" / "marker.txt", Bytes("keep"));
  EXPECT_THROW(signing::sign_model_bundle_directory(
                   base_ / "unsigned", source.manifest_digest,
                   base_ / "existing", Signer(), Policy()),
               jyppx::liuding::Error);
  EXPECT_TRUE(std::filesystem::exists(base_ / "existing" / "marker.txt"));
  EXPECT_THROW(signing::sign_model_bundle_directory(
                   base_ / "unsigned", source.manifest_digest,
                   base_ / "unsigned" / "nested", Signer(), Policy()),
               jyppx::liuding::InvalidArgument);
  EXPECT_THROW(
      signing::sign_model_bundle_directory(
          base_ / "unsigned", source.manifest_digest, base_ / "wrong-key",
          signing::Ed25519Signer::generate(), Policy()),
      jyppx::liuding::InvalidArgument);
  EXPECT_THROW(signing::sign_model_bundle_directory(
                   base_ / "unsigned", source.manifest_digest,
                   base_ / "revoked", Signer(), Policy(true)),
               jyppx::liuding::InvalidArgument);
  EXPECT_THROW(signing::sign_model_bundle_directory(
                   base_ / "unsigned", Digest(Bytes("wrong")),
                   base_ / "bad-sha", Signer(), Policy()),
               jyppx::liuding::Error);
  EXPECT_FALSE(std::filesystem::exists(base_ / "bad-sha"));
  auto limits = interop::ModelBundleLimits{};
  limits.max_signatures = 0U;
  EXPECT_THROW(signing::sign_model_bundle_directory(
                   base_ / "unsigned", source.manifest_digest,
                   base_ / "limited", Signer(), Policy(), limits),
               jyppx::liuding::Error);
  EXPECT_FALSE(std::filesystem::exists(base_ / "limited"));
}

TEST_F(BundleSigningDirectory,
       PrivateKeyAndPolicyFilesRejectLinksAndDirectories) {
  const auto key = base_ / "inputs" / "private.pem";
  Write(key, Bytes(Pem()));
  EXPECT_EQ(signing::Ed25519Signer::from_pkcs8_file(key).public_key(),
            Public());
  const auto json = signing::serialize_ed25519_trust_policy(Public());
  const auto policy = base_ / "inputs" / "policy.json";
  Write(policy, Bytes(json));
  EXPECT_EQ(signing::Ed25519TrustPolicy::load(policy, Digest(Bytes(json)))
                .public_key(),
            Public());
  EXPECT_THROW(signing::Ed25519Signer::from_pkcs8_file(base_ / "inputs"),
               jyppx::liuding::IoError);
  const auto hard = base_ / "hard.pem";
  std::error_code error;
  std::filesystem::create_hard_link(key, hard, error);
  if (error)
    GTEST_SKIP() << "Filesystem does not permit hard-link negative fixture";
  EXPECT_THROW(signing::Ed25519Signer::from_pkcs8_file(hard),
               jyppx::liuding::IoError);
  EXPECT_THROW(signing::Ed25519Signer::from_pkcs8_file(key),
               jyppx::liuding::IoError);
  std::filesystem::remove(hard);
  const auto link = base_ / "link.pem";
  std::filesystem::create_symlink(key, link, error);
  if (error)
    GTEST_SKIP() << "Filesystem/user does not permit symlink negative fixture";
  EXPECT_THROW(signing::Ed25519Signer::from_pkcs8_file(link),
               jyppx::liuding::IoError);
  const auto directory_link = base_ / "linked-directory";
  std::filesystem::create_directory_symlink(base_ / "inputs", directory_link,
                                            error);
  ASSERT_FALSE(error);
  EXPECT_THROW(
      signing::Ed25519Signer::from_pkcs8_file(directory_link / "private.pem"),
      jyppx::liuding::IoError);
  EXPECT_THROW(signing::Ed25519TrustPolicy::load(directory_link / "policy.json",
                                                 Digest(Bytes(json))),
               jyppx::liuding::IoError);
}

