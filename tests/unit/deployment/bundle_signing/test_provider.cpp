TEST_F(BundleSigningDirectory, SignsNewDirectoryWithPinnedSourceAndRealTrust) {
  const auto result = PublishSigned();
  EXPECT_EQ(result.published.signature_status,
            interop::BundleSignatureStatus::trusted);
  EXPECT_EQ(result.trust_policy_digest, Policy().digest());
  EXPECT_EQ(result.key_id, Policy().key_id());
  EXPECT_EQ(interop::model_bundle_signing_payload(manifest_),
            interop::model_bundle_signing_payload(result.published.manifest));
  EXPECT_EQ(result.published.manifest.signatures[0].signature_hex,
            Signer().sign_manifest(manifest_).signature_hex);
  EXPECT_EQ(interop::verify_model_bundle_directory(base_ / "unsigned")
                .signature_status,
            interop::BundleSignatureStatus::unsigned_bundle);
  EXPECT_EQ(interop::verify_model_bundle_directory(
                base_ / "signed", signing::trusted_ed25519_options(Policy()))
                .signature_status,
            interop::BundleSignatureStatus::trusted);
  EXPECT_EQ(
      interop::verify_model_bundle_directory(base_ / "signed").signature_status,
      interop::BundleSignatureStatus::present_unverified);
  const auto second = signing::sign_model_bundle_directory(
      base_ / "signed", result.published.manifest_digest,
      base_ / "signed-again", Signer(), Policy());
  EXPECT_EQ(second.published.manifest.signatures.size(), 1U);
  EXPECT_EQ(second.published.manifest.signatures[0].signature_hex,
            result.published.manifest.signatures[0].signature_hex);
}

