"""Generate and verify the fixed torchvision ResNeXt50-32x4d random reference."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import subprocess
import xml.etree.ElementTree as ET


ARCHITECTURE = "resnext50_32x4d"
TEST_NAME = "ModelsPythonInterop.OfficialTorchvisionResNeXt50ReferenceReallyRuns"
VERSIONS = {
    "python": "3.13.12",
    "torch": "2.9.1+cpu",
    "torchvision": "0.24.1+cpu",
    "safetensors": "0.8.0",
}

FROZEN_FILES = {
    "resnext50_32x4d-input.safetensors": {
        "size_bytes": 49232,
        "sha256": "6b99dcc49601e1640ae223963afa0639e7091c50f07e1c6bf98bcf96667375a8",
    },
    "resnext50_32x4d-output.safetensors": {
        "size_bytes": 495912,
        "sha256": "dec808139cf1bb6c4d18fc4594afabd00e0b62d0a245aa029a7539cfff1aefdd",
    },
    "resnext50_32x4d-state.safetensors": {
        "size_bytes": 100417784,
        "sha256": "8540deaf5deda4e829592f52bd3a79e9955ee183397bdf93c867d0851f648826",
    },
}


def digest(path: Path) -> str:
    result = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            result.update(chunk)
    return result.hexdigest()


def verify_files(directory: Path) -> dict:
    if len(FROZEN_FILES) != 3:
        raise ValueError("The three reviewed reference identities are required")
    for name, identity in FROZEN_FILES.items():
        path = directory / name
        if path.stat().st_size != identity["size_bytes"] or digest(path) != identity["sha256"]:
            raise ValueError("Fixed reference identity mismatch: " + name)
    return FROZEN_FILES


def generate(directory: Path) -> dict:
    import torch
    import torchvision
    import safetensors
    from safetensors.torch import save_file

    observed = {
        "python": platform.python_version(),
        "torch": torch.__version__,
        "torchvision": torchvision.__version__,
        "safetensors": safetensors.__version__,
    }
    if observed != VERSIONS:
        raise ValueError(f"Reference toolchain differs: {observed}")
    torch.set_num_threads(2)
    torch.set_num_interop_threads(1)
    torch.manual_seed(1729)
    model = torchvision.models.resnext50_32x4d(weights=None).eval()
    input_image = torch.randn((1, 3, 64, 64), dtype=torch.float32)
    stages = {}
    handles = []
    for stage_name in ("layer1", "layer2", "layer3", "layer4"):
        def capture(_module, _inputs, result, key=stage_name):
            stages[key] = result.detach().cpu().contiguous()
        handles.append(getattr(model, stage_name).register_forward_hook(capture))
    with torch.inference_mode():
        logits = model(input_image)
    for handle in handles:
        handle.remove()
    for role, tensors in (
        ("state", model.state_dict()),
        ("input", {"input": input_image}),
        ("output", {"output": logits, **stages}),
    ):
        save_file({key: value.detach().cpu().contiguous()
                   for key, value in tensors.items()},
                  str(directory / f"{ARCHITECTURE}-{role}.safetensors"))
    files = {path.name: {"size_bytes": path.stat().st_size,
                         "sha256": digest(path)}
             for path in directory.glob(ARCHITECTURE + "-*.safetensors")}
    if FROZEN_FILES and files != FROZEN_FILES:
        raise ValueError("Generated bytes differ from the reviewed fixed identities")
    return {
        "schema_id": "jyppx.models.resnext-generation",
        "schema_version": 1,
        "generator_sha256": digest(Path(__file__)),
        "platform": platform.platform(),
        "versions": observed,
        "seed": 1729,
        "reference_source": "torchvision.models.resnext50_32x4d(weights=None)",
        "pretrained": False,
        "parameters": sum(value.numel() for value in model.parameters()),
        "state_tensors": len(model.state_dict()),
        "input_shape": list(input_image.shape),
        "output_shape": list(logits.shape),
        "stage_shapes": {key: list(value.shape) for key, value in stages.items()},
        "files": files,
    }


def verify_cpp(executable: Path, directory: Path) -> dict:
    files = verify_files(directory)
    environment = dict(os.environ)
    environment["JYPPX_LIUDING_RESNEXT_REFERENCE_DIR"] = str(directory)
    xml_path = directory / "resnext-cpp-test.xml"
    log_path = directory / "resnext-cpp-test.log"
    xml_path.unlink(missing_ok=True)
    log_path.unlink(missing_ok=True)
    with log_path.open("w", encoding="utf-8") as stream:
        result = subprocess.run(
            [str(executable.resolve(strict=True)), "--gtest_filter=" + TEST_NAME,
             "--gtest_output=xml:" + str(xml_path)],
            env=environment, stdout=stream, stderr=subprocess.STDOUT,
            check=False, timeout=300,
        )
    if result.returncode != 0:
        raise ValueError("C++ ResNeXt differential failed: " + str(log_path))
    cases = ET.parse(xml_path).getroot().findall(".//testcase")
    if (len(cases) != 1 or
            cases[0].get("classname", "") + "." + cases[0].get("name", "") != TEST_NAME or
            cases[0].get("status") != "run" or
            any(cases[0].find(tag) is not None for tag in ("skipped", "failure", "error"))):
        raise ValueError("The exact C++ ResNeXt test must pass without skips")
    verify_files(directory)
    return {
        "schema_id": "jyppx.models.resnext-cpp-reference",
        "schema_version": 1,
        "platform": platform.platform(),
        "generator_sha256": digest(Path(__file__)),
        "files": files,
        "test": TEST_NAME,
        "status": "passed",
        "executable_sha256": digest(executable),
        "xml_sha256": digest(xml_path),
        "log_sha256": digest(log_path),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixture-dir", required=True, type=Path)
    parser.add_argument("--verify-only", action="store_true")
    parser.add_argument("--cpp-test-executable", type=Path)
    args = parser.parse_args()
    directory = args.fixture_dir.resolve()
    if args.verify_only:
        verify_files(directory)
    else:
        directory.mkdir(parents=True, exist_ok=True)
        report = generate(directory)
        (directory / "resnext-generation-evidence.json").write_text(
            json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if args.cpp_test_executable:
        report = verify_cpp(args.cpp_test_executable, directory)
        (directory / "resnext-cpp-evidence.json").write_text(
            json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        print(json.dumps({"status": "passed", "test": TEST_NAME}, sort_keys=True))
    else:
        print(json.dumps({"status": "fixtures-verified" if args.verify_only else "generated"},
                         sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
